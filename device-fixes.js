DJARB.renderDeviceFixes = function() {
  const container = document.getElementById('deviceFixesContainer');
  if (!container) return;
  
  let html = '';
  
  Object.keys(DJARB.DEVICE_FIXES).forEach(device => {
    const deviceName = device.charAt(0).toUpperCase() + device.slice(1);
    const fixes = DJARB.DEVICE_FIXES[device];
    
    html += `
      <div class="device-section" id="device-${device}">
        <h3 class="device-title">${deviceName}</h3>
        <div class="device-fixes-list">
    `;
    
    fixes.forEach((fix, index) => {
      const sevClass = fix.sev || 'info';
      html += `
          <div class="device-fix-item fix-${sevClass}">
            <div class="fix-header">
              <span class="fix-number">${index + 1}</span>
              <h4>${fix.title}</h4>
              <span class="fix-sev sev-${sevClass}">${sevClass === 'crit' ? 'Критично' : sevClass === 'warn' ? 'Важно' : 'Информация'}</span>
            </div>
            <div class="fix-symptom">
              <strong>Симптом:</strong> ${fix.symptom}
            </div>
            <div class="fix-cause">
              <strong>Причина:</strong> ${fix.cause}
            </div>
            <div class="fix-explanation">
              <strong>Простыми словами:</strong> ${fix.plain}
            </div>
            <div class="fix-solution">
              <strong>Решение:</strong>
              <ol>
                ${fix.fix.map(step => `<li>${step}</li>`).join('')}
              </ol>
            </div>
          </div>
      `;
    });
    
    html += `
        </div>
      </div>
    `;
  });
  
  container.innerHTML = html;
};